@runtime_checkable
class AuthStoreProtocol(Protocol):
    """users, tokens and workspace_tokens. A duplicate username raises
    `warren.state.errors.StateConflict` from the DynamoDB store and
    `sqlite3.IntegrityError` from the SQLite one; callers catch both."""

    async def close(self) -> None: ...
    async def create_user(self, *, username: str, is_admin: bool) -> User: ...
    async def get_user(self, user_id: str) -> User | None: ...
    async def get_user_by_username(self, username: str) -> User | None: ...
    async def list_users(self) -> list[User]: ...
    async def disable_user(self, user_id: str, *, keep_last_admin: bool = False) -> bool: ...
    async def enable_user(self, user_id: str) -> bool: ...
    async def count_admins(self) -> int: ...
    async def count_enabled_admins(self) -> int: ...
    async def list_admins(self) -> list[User]: ...

    async def create_token(
        self,
        *,
        user_id: str,
        hashed_token: str,
        expires_at: datetime | None = None,
        created_by_token_id: str | None = None,
        max_active: int | None = None,
        scope: str = "full",
    ) -> Token: ...

    async def list_tokens_for_user(self, user_id: str) -> list[Token]: ...
    async def count_active_tokens_for_user(self, user_id: str) -> int: ...
    async def revoke_all_tokens_for_user(self, user_id: str) -> int: ...
    async def get_active_user_by_hashed_token(self, hashed_token: str) -> User | None: ...

    async def get_active_user_and_token_id_by_hashed_token(
        self, hashed_token: str
    ) -> tuple[User, str] | None: ...

    async def get_active_user_and_token_by_hashed_token(
        self, hashed_token: str
    ) -> tuple[User, Token] | None: ...

    async def get_token(self, token_id: str) -> Token | None: ...
    async def revoke_token_lineage(self, token_id: str) -> int: ...
    async def revoke_token(self, token_id: str) -> bool: ...

    async def create_workspace_token(
        self,
        *,
        workspace_id: str,
        user_id: str,
        hashed_token: str,
        expires_at: datetime,
        public_key: str | None = None,
        created_by_token_id: str | None = None,
        provision_grant: bool = False,
    ) -> WorkspaceToken: ...

    async def get_active_workspace_token(self, hashed_token: str) -> tuple[User, WorkspaceToken] | None: ...
    async def consume_provision_grant(self, token_id: str) -> bool: ...
    async def revoke_workspace_tokens(self, workspace_id: str, *, keep_token_id: str | None = None) -> int: ...


@runtime_checkable
class SecretStoreProtocol(Protocol):
    """Per-owner secrets keyed by (owner_id, name). Never returns another owner's."""

    async def set(self, owner_id: str, name: str, value: str) -> None: ...
    async def exists(self, owner_id: str, name: str) -> bool: ...
    async def delete(self, owner_id: str, name: str) -> bool: ...
    async def list(self, owner_id: str) -> list[dict[str, str]]: ...
    async def resolve(self, owner_id: str, names: list[str]) -> dict[str, str]: ...

    async def reencrypt(self, owner_id: str, name: str) -> bool:
        """Re-encrypt the stored value under the current key without changing it.
        False when the secret doesn't exist."""
        ...

    async def count(self) -> int: ...

    async def owners_with(self, name: str) -> set[str]:
        """Every owner that has a secret called `name` (warren.notify: who has a webhook).
        Names only, never values."""
        ...


@runtime_checkable
class RunStoreProtocol(Protocol):
    """Headless runs (registry/runs.py), keyed by run id (= workspace id). Rows outlive
    their workspace; `prune` drops finished ones by age and per-owner count."""

    async def create(
        self,
        *,
        run_id: str,
        owner_id: str,
        project: str,
        template: str,
        timeout_seconds: float | None,
        started_at: datetime | None = None,
    ) -> None: ...

    async def get(self, run_id: str) -> dict[str, Any] | None: ...
    async def list(self, owner_id: str | None, limit: int = 50) -> list[dict[str, Any]]: ...

    async def finish(
        self, run_id: str, *, status: str, result: dict[str, Any], ended_at: datetime | None = None
    ) -> bool: ...

    async def prune(
        self, *, retention_seconds: float, max_per_owner: int, now: datetime | None = None
    ) -> int: ...
